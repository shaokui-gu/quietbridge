def temp_parent():
    """Return a real (symlink-free) parent for the throwaway temp root.

    The lifecycle store refuses any path with a symlink component, and macOS
    TMPDIR commonly lives below /var, which is itself a symlink. Prefer
    /private/tmp and fall back to the resolved TMPDIR.
    """
    candidates = [Path('/private/tmp')]
    try:
        candidates.append(Path(tempfile.gettempdir()).resolve())
    except OSError:
        pass
    for candidate in candidates:
        try:
            if candidate.is_dir() and not candidate.is_symlink():
                return candidate.resolve()
        except OSError:
            continue
    raise RuntimeError('没有可用的临时目录（/private/tmp 与 TMPDIR 均不可用）')


def real_dsh_home():
    return (Path.home() / '.dsh').resolve()


def unsafe_home(value):
    """True when DSH_HOME touches the real ~/.dsh (or the user home itself)."""
    try:
        target = Path(value).expanduser().resolve()
    except (OSError, RuntimeError):
        return True
    real = real_dsh_home()
    return target == real or real in target.parents or target in real.parents


def python_executable():
    candidate = sys.executable
    if candidate and Path(candidate).is_file():
        return str(Path(candidate).resolve())
    found = shutil.which('python3') or shutil.which('python')
    return str(Path(found).resolve()) if found else None


def preflight(args):
    """Return (app, cli, skip_reason); skip_reason is set when the host is absent."""
    if sys.platform != 'darwin':
        return None, None, '仅支持 macOS；当前平台是 ' + sys.platform
    target = Path(args.app).expanduser()
    if target.is_file():
        app, cli = None, target
    else:
        app, cli = target, target / CLI_PATH
    if app is not None and not app.is_dir():
        return app, None, '未找到 DeepSeek Harness 应用：%s（可用 --app 指定）' % app
    if not cli.is_file():
        return app, cli, '未找到 DSH CLI：%s' % cli
    if not os.access(str(cli), os.X_OK):
        return app, cli, 'DSH CLI 不可执行：%s' % cli
    return app, cli, None


def child_env(home):
    """A hermetic environment: temp DSH_HOME, no inherited QuietBridge identity."""
    env = {key: value for key, value in os.environ.items()
           if key != 'DSH_HOME' and key != 'PYTHONPATH'
           and not key.startswith('QUIETBRIDGE_') and not key.startswith('CUA_')}
    env['DSH_HOME'] = str(home)
    env['PYTHONDONTWRITEBYTECODE'] = '1'
    return env


def run_step(label, command, *, env, cwd, timeout, diagnostics):
    display = shlex.join([str(part) for part in command])
    log('%s：%s' % (label, display))
    try:
        completed = subprocess.run(
            [str(part) for part in command], cwd=str(cwd), env=env,
            stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            timeout=timeout, text=True, errors='replace',
        )
    except subprocess.TimeoutExpired as error:
        record = {'label': label, 'command': display, 'timeoutSeconds': timeout,
                  'stdout': clip(as_text(error.stdout)), 'stderr': clip(as_text(error.stderr))}
        diagnostics.setdefault('commands', []).append(record)
        raise SetupError('%s 超时（%ss）；命令：%s' % (label, timeout, display))
    except OSError as error:
        raise SetupError('%s 无法执行：%s；命令：%s' % (label, error, display))
    record = {'label': label, 'command': display, 'returncode': completed.returncode,
              'stdout': clip(completed.stdout), 'stderr': clip(completed.stderr)}
    diagnostics.setdefault('commands', []).append(record)
    if completed.returncode != 0:
        raise SetupError(
            '%s 失败（exit %s）\n命令：%s\nstdout:\n%s\nstderr:\n%s'
            % (label, completed.returncode, display,
               clip(completed.stdout), clip(completed.stderr)))
    return completed


def create_profile(cli, home, profile, *, root, env, diagnostics):
    home.mkdir(mode=0o700, parents=True, exist_ok=True)
    run_step('创建隔离 profile（web 模板）',
             [cli, '--profile', profile, '--from-default-profile', 'web', '--dump-config'],
             env=env, cwd=root, timeout=SETUP_TIMEOUT, diagnostics=diagnostics)
    profile_dir = home / 'profiles' / profile
    if not (profile_dir / 'package.json').is_file():
        raise SetupError('profile 创建后缺少 package.json：%s' % profile_dir)
    log('隔离 profile 已创建：%s' % profile_dir)
    return profile_dir


def render_bundle(root, config_dir, python):
    source = ROOT / BUNDLE_SOURCE
    connector = ROOT / CONNECTOR
    if not (source / 'package.json').is_file():
        raise SetupError('缺少 bundle 模板：%s' % (source / 'package.json'))
    if not connector.is_file():
        raise SetupError('缺少 connector 入口：%s' % connector)
    if not (ROOT / LIFECYCLE).is_file():
        raise SetupError('缺少 lifecycle CLI：%s' % (ROOT / LIFECYCLE))
    try:
        sys.path.insert(0, str(ROOT))
        from adapters.deepseek_harness.configuration import bundle_render
    except Exception as error:  # noqa: BLE001 - report the import problem verbatim
        raise SetupError('无法导入 adapters.deepseek_harness.configuration：%r' % (error,))
    config_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    helper = root / 'missing-helper'
    if helper.exists():
        raise SetupError('测试 helper 路径意外存在（本应不存在）：%s' % helper)
    destination = root / 'bundle'
    try:
        plan = bundle_render(source, destination, python=python, connector=connector,
                             helper=helper, config_dir=config_dir, apply=True)
    except (ValueError, OSError) as error:
        raise SetupError('bundle_render 失败：%s' % error)
    patch_file = destination / 'cordis.patch.yml'
    try:
        patch = patch_file.read_text(encoding='utf-8')
    except OSError as error:
        raise SetupError('渲染后的 bundle 缺少 cordis.patch.yml：%s' % error)
    if str(helper) not in patch or 'quietbridge-dsh' not in patch or str(config_dir) not in patch:
        raise SetupError('渲染后的 bundle patch 未包含预期的 helper/configDir 配置')
    log('已渲染 bundle：%s（helper 故意缺失：%s）' % (destination, helper))
    return destination, plan


