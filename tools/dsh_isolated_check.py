def terminate(proc):
    if proc is None or proc.poll() is not None:
        return
    try:
        os.killpg(os.getpgid(proc.pid), signal.SIGTERM)
    except OSError:
        try:
            proc.terminate()
        except OSError:
            pass
    try:
        proc.wait(timeout=10)
    except subprocess.TimeoutExpired:
        try:
            os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
        except OSError:
            try:
                proc.kill()
            except OSError:
                pass
        try:
            proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            pass


def boot_host(cli, profile, overlay, *, root, home, timeout, result_path, diagnostics):
    boot_dir = root / 'run'
    boot_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    out_path, err_path = root / 'boot.out', root / 'boot.err'
    command = [str(cli), '--profile', profile, '--patch', str(overlay), '--no-open', '--port', '0']
    log('启动隔离宿主：%s' % shlex.join(command))
    boot = {'command': shlex.join(command), 'exitCode': None, 'timedOut': False,
            'killedAfterResult': False, 'resultReady': False, 'exitedEarly': False,
            'stdout': '', 'stderr': ''}
    out = out_path.open('w', encoding='utf-8', errors='replace')
    err = err_path.open('w', encoding='utf-8', errors='replace')
    proc = None
    try:
        try:
            proc = subprocess.Popen(
                command, cwd=str(boot_dir), env=child_env(home),
                stdin=subprocess.DEVNULL, stdout=out, stderr=err, start_new_session=True,
            )
        except OSError as error:
            raise SetupError('宿主启动失败：%s' % error)
        deadline = time.monotonic() + timeout
        while True:
            report = read_json(result_path)
            if isinstance(report, dict) and (report.get('done') is True or report.get('fatal')):
                boot['resultReady'] = True
                grace = time.monotonic() + PROBE_EXIT_GRACE
                while proc.poll() is None and time.monotonic() < grace:
                    time.sleep(0.2)
                if proc.poll() is None:
                    boot['killedAfterResult'] = True
                break
            if proc.poll() is not None:
                boot['exitedEarly'] = True
                report = read_json(result_path)
                boot['resultReady'] = isinstance(report, dict) and (
                    report.get('done') is True or bool(report.get('fatal')))
                break
            if time.monotonic() >= deadline:
                boot['timedOut'] = True
                break
            time.sleep(0.25)
    finally:
        if proc is not None and proc.poll() is None:
            terminate(proc)
        if proc is not None:
            try:
                boot['exitCode'] = proc.wait(timeout=10)
            except subprocess.TimeoutExpired:
                terminate(proc)
                boot['exitCode'] = proc.poll()
        out.close()
        err.close()
    boot['stdout'] = as_text(out_path.read_text(encoding='utf-8', errors='replace'))
    boot['stderr'] = as_text(err_path.read_text(encoding='utf-8', errors='replace'))
    log('宿主已退出：exit=%s%s%s'
        % (boot['exitCode'], '（超时被结束）' if boot['timedOut'] else '',
           '（探针完成后仍未退出，已结束）' if boot['killedAfterResult'] else ''))
    diagnostics['boot'] = boot
    return boot


def turns_map(state):
    turns = state.get('turns') if isinstance(state, dict) else None
    return turns if isinstance(turns, dict) else {}


def find_turn(state, request_id):
    for turn in turns_map(state).values():
        if isinstance(turn, dict) and turn.get('requestId') == request_id:
            return turn
    return None


def find_tombstone(state, session):
    for turn in turns_map(state).values():
        if (isinstance(turn, dict) and turn.get('requestId') is None
                and turn.get('sessionEnded') is True
                and turn.get('stoppedAt') is not None
                and turn.get('sessionId') == session):
            return turn
    return None


def check_boot(failures, boot, timeout):
    if boot.get('timedOut') is True:
        failures.append('宿主在 %ss 内未完成探针，已被超时结束' % timeout)
    if boot.get('killedAfterResult') is True:
        failures.append('探针完成后宿主进程未退出，已被强制结束')
    if boot.get('exitCode') != 0:
        failures.append('宿主退出码为 %r（期望 0；探针完成时应 process.exit(0)）'
                        % (boot.get('exitCode'),))


def evaluate_single(report, state, boot, timeout, state_path):
    failures = []
    evidence = {'statePath': str(state_path)}

    def check(condition, message):
        if not condition:
            failures.append(message)

    if not isinstance(report, dict):
        report = {}
        check(False, '探针未写出可解析的结果文件')
    check(report.get('done') is True, '探针未标记完成（done 缺失或为 false）')
    check(not report.get('fatal'), '探针报错：%s' % clip(str(report.get('fatal') or ''), 1500))
    check(report.get('created') is True, '探针未能创建 Agent（created 不是 true）')
    check(report.get('toolPresent') is True, '探针通过 ctx.tools.get() 取不到 quietbridge_permissions')
    check(report.get('disposed') is True, '探针未能 dispose Agent')

    tools = report.get('tools') if isinstance(report.get('tools'), list) else []
    evidence['toolCount'] = report.get('toolCount')
    evidence['tools'] = tools
    check(isinstance(report.get('toolCount'), int) and report['toolCount'] >= 19,
          '工具数量不足 19：%r' % (report.get('toolCount'),))
    missing = sorted(REQUIRED_TOOLS - {str(name) for name in tools})
    check(not missing, '缺少 quietbridge_* 工具：%s' % ', '.join(missing))

    live = report.get('liveTurnCall') if isinstance(report.get('liveTurnCall'), dict) else {}
    live_error = as_text(live.get('error'))
    evidence['liveTurnError'] = live_error
    check(live.get('ok') is False, '活动 turn 内调用 quietbridge_permissions 没有失败')
    check('HELPER_MISSING' in live_error,
          '活动 turn 调用未返回 HELPER_MISSING：%s' % clip(live_error, 500))
    check('SESSION_ROUTING_REQUIRED' not in live_error,
          '活动 turn 调用被路由拒绝（SESSION_ROUTING_REQUIRED），而不是缺 helper')

    stopped = report.get('stoppedTurnCall') if isinstance(report.get('stoppedTurnCall'), dict) else {}
    stopped_error = as_text(stopped.get('error'))
    evidence['stoppedTurnError'] = stopped_error
    check(stopped.get('ok') is False, 'turn 结束后调用 quietbridge_permissions 没有失败')
    check('TASK_CANCELLED' in stopped_error,
          'turn 结束后调用未返回 TASK_CANCELLED：%s' % clip(stopped_error, 500))

    agent = report.get('agent') if isinstance(report.get('agent'), dict) else {}
    session = agent.get('sessionId') if isinstance(agent.get('sessionId'), str) else None
    evidence['sessionId'] = session
    if not session:
        failures.append('探针未报告 agent.session.id')
    if not state_path.is_file():
        failures.append('lifecycle state 文件不存在：%s' % state_path)
    turns = turns_map(state)
    if not isinstance(state, dict) or not isinstance(state.get('turns'), dict):
        failures.append('lifecycle state 缺少 turns 映射（%s）' % state_path)
    evidence['turnCount'] = len(turns)
    request_ids = [turn.get('requestId') for turn in turns.values() if isinstance(turn, dict)]
    evidence['requestIds'] = sorted(request_ids,
                                    key=lambda value: '' if value is None else str(value))[:20]
    evidence['lifecycleCalls'] = report.get('lifecycleCalls')
    if session:
        expected = session + ':90'
        turn = find_turn(state, expected)
        check(turn is not None, 'lifecycle state 缺少 requestId=%s 的 turn' % expected)
        if isinstance(turn, dict):
            check(turn.get('stoppedAt') is not None,
                  'lifecycle turn %s 缺少 stoppedAt（turn-end 未落盘）' % expected)
            evidence['turn90'] = {'requestId': turn.get('requestId'),
                                  'stoppedAt': turn.get('stoppedAt'),
                                  'reason': turn.get('reason'),
                                  'sessionEnded': turn.get('sessionEnded')}
        tombstone = find_tombstone(state, session)
        check(tombstone is not None,
              'lifecycle state 缺少 sessionEnded tombstone（agent-disposed 未落盘）')
        if isinstance(tombstone, dict):
            evidence['tombstone'] = {'requestId': tombstone.get('requestId'),
                                     'reason': tombstone.get('reason'),
                                     'sessionEnded': tombstone.get('sessionEnded'),
                                     'stoppedAt': tombstone.get('stoppedAt')}

    check_boot(failures, boot, timeout)
    return failures, evidence


def evaluate_multi(report, state, boot, timeout, state_path, agents_n):
    failures = []
    evidence = {'statePath': str(state_path), 'agents': [], 'concurrency': None,
                'capacity': None, 'definitionIsolation': None}

    def check(condition, message):
        if not condition:
            failures.append(message)

    if not isinstance(report, dict):
        report = {}
        check(False, '探针未写出可解析的结果文件')
    check(report.get('done') is True, '探针未标记完成（done 缺失或为 false）')
    check(not report.get('fatal'), '探针报错：%s' % clip(str(report.get('fatal') or ''), 1500))
    check(report.get('created') is True, '探针未能创建全部 Agent（created 不是 true）')
    check(report.get('allDisposed') is True, '探针未能 dispose 全部 Agent')
    if not state_path.is_file():
        failures.append('lifecycle state 文件不存在：%s' % state_path)
    state_turns = turns_map(state)
    evidence['turnCount'] = len(state_turns)
    request_ids = [turn.get('requestId') for turn in state_turns.values() if isinstance(turn, dict)]
    evidence['requestIds'] = sorted(request_ids,
                                    key=lambda value: '' if value is None else str(value))[:40]
    evidence['definitionIsolation'] = report.get('definitionIsolation')
    working_count = min(agents_n, CAPACITY_LIMIT)
    evidence['capacity'] = {'maxConnectors': CAPACITY_LIMIT, 'requested': agents_n,
                            'degraded': agents_n > CAPACITY_LIMIT,
                            'workingAgents': working_count}

    agents = report.get('agents') if isinstance(report.get('agents'), list) else []
    check(len(agents) == agents_n, '探针报告了 %d 个 Agent（期望 %d）' % (len(agents), agents_n))
    seen_ids, seen_sessions = set(), set()
    working_fingerprints = set()
    for position in range(agents_n):
        record = agents[position] if position < len(agents) else {}
        index = position + 1
        session = record.get('sessionId') if isinstance(record.get('sessionId'), str) else None
        agent_id = record.get('id') if isinstance(record.get('id'), str) else None
        live = record.get('liveTurnCall') if isinstance(record.get('liveTurnCall'), dict) else {}
        stopped = record.get('stoppedTurnCall') if isinstance(record.get('stoppedTurnCall'), dict) else {}
        entry = {
            'index': index,
            'id': agent_id,
            'sessionId': session,
            'toolCount': record.get('toolCount'),
            'toolFingerprint': record.get('toolFingerprint'),
            'definitionCount': record.get('definitionCount'),
            'toolPresent': record.get('toolPresent') is True,
            'liveTurnError': as_text(live.get('error')),
            'stoppedTurnError': as_text(stopped.get('error')),
            'disposed': record.get('disposed') is True,
            'capacityDegraded': index > CAPACITY_LIMIT,
        }
        check(bool(record), '缺少 Agent%d 的记录' % index)
        if record:
            check(record.get('created') is True, 'Agent%d 未创建成功' % index)
            check(bool(session), 'Agent%d 缺少 sessionId' % index)
            check(bool(agent_id), 'Agent%d 缺少 agent id' % index)
            check(session not in seen_sessions and agent_id not in seen_ids,
                  'Agent%d 的 id/sessionId 与其他 Agent 重复' % index)
            if session:
                seen_sessions.add(session)
            if agent_id:
                seen_ids.add(agent_id)
            if index <= CAPACITY_LIMIT:
                names = {str(name) for name in record.get('tools') or []}
                check(isinstance(record.get('toolCount'), int) and record['toolCount'] >= 19,
                      'Agent%d 工具数量不足 19：%r' % (index, record.get('toolCount')))
                missing = sorted(REQUIRED_TOOLS - names)
                check(not missing, 'Agent%d 缺少 quietbridge_* 工具：%s'
                      % (index, ', '.join(missing)))
                check(record.get('toolPresent') is True,
                      'Agent%d 通过 ctx.tools.get() 取不到 quietbridge_permissions' % index)
                working_fingerprints.add(record.get('toolFingerprint'))
                live_error = as_text(live.get('error'))
                check(live.get('ok') is False, 'Agent%d 活动 turn 调用没有失败' % index)
                check('HELPER_MISSING' in live_error,
                      'Agent%d 活动 turn 调用未返回 HELPER_MISSING：%s'
                      % (index, clip(live_error, 400)))
                check('SESSION_ROUTING_REQUIRED' not in live_error,
                      'Agent%d 活动 turn 调用被路由拒绝（SESSION_ROUTING_REQUIRED）' % index)
                stopped_error = as_text(stopped.get('error'))
                check(stopped.get('ok') is False, 'Agent%d turn 结束后调用没有失败' % index)
                check('TASK_CANCELLED' in stopped_error,
                      'Agent%d turn 结束后调用未返回 TASK_CANCELLED：%s'
                      % (index, clip(stopped_error, 400)))
                check(record.get('disposed') is True, 'Agent%d 未被 dispose' % index)
                expected = (session or '') + ':90'
                turn = find_turn(state, expected) if session else None
                check(turn is not None,
                      'lifecycle state 缺少 Agent%d 的 turn %s' % (index, expected))
                if isinstance(turn, dict):
                    check(turn.get('stoppedAt') is not None,
                          'lifecycle turn %s 缺少 stoppedAt（Agent%d turn-end 未落盘）'
                          % (expected, index))
                    entry['turn90'] = {
                        'requestId': turn.get('requestId'),
                        'stoppedAt': turn.get('stoppedAt'),
                        'reason': turn.get('reason'),
                        'sessionEnded': turn.get('sessionEnded'),
                    }
                tombstone = find_tombstone(state, session) if session else None
                check(tombstone is not None,
                      'lifecycle state 缺少 Agent%d 的 sessionEnded tombstone' % index)
                if isinstance(tombstone, dict):
                    entry['tombstone'] = {
                        'requestId': tombstone.get('requestId'),
                        'reason': tombstone.get('reason'),
                        'sessionEnded': tombstone.get('sessionEnded'),
                    }
            else:
                check(record.get('toolCount') == 0,
                      '第 %d 个 Agent 超出 maxConnectors=%d 却注册了 %r 个工具'
                      % (index, CAPACITY_LIMIT, record.get('toolCount')))
                check(not record.get('tools'),
                      '第 %d 个 Agent 超出容量却报告了工具' % index)
                check(record.get('toolPresent') is not True,
                      '第 %d 个 Agent 超出容量却取到了 quietbridge_permissions' % index)
        evidence['agents'].append(entry)

    check(len(working_fingerprints) <= 1,
          '工作 Agent 的工具 definition 集不一致：%r' % (sorted(working_fingerprints),))

    concurrency = report.get('concurrency') if isinstance(report.get('concurrency'), dict) else {}
    evidence['concurrency'] = concurrency
    if agents_n >= 2:
        after_stop = concurrency.get('afterStopA') if isinstance(concurrency.get('afterStopA'), dict) else {}
        first_stopped = after_stop.get('agent1Stopped') if isinstance(after_stop.get('agent1Stopped'), dict) else {}
        second_live = after_stop.get('agent2Live') if isinstance(after_stop.get('agent2Live'), dict) else {}
        first_error = as_text(first_stopped.get('error'))
        second_error = as_text(second_live.get('error'))
        check(first_stopped.get('ok') is False and 'TASK_CANCELLED' in first_error,
              '停止 Agent1 turn 后，Agent1 未被 TASK_CANCELLED 拒绝：%s'
              % clip(first_error, 400))
        check(second_live.get('ok') is False and 'HELPER_MISSING' in second_error,
              '停止 Agent1 turn 后，Agent2 的 live turn 未返回 HELPER_MISSING：%s'
              % clip(second_error, 400))
        check('SESSION_ROUTING_REQUIRED' not in second_error,
              '停止 Agent1 turn 后，Agent2 的 live turn 被路由拒绝'
              '（SESSION_ROUTING_REQUIRED）')

        after_dispose = (concurrency.get('afterDisposeA')
                         if isinstance(concurrency.get('afterDisposeA'), dict) else {})
        tombstone = after_dispose.get('agent1Tombstone')
        check(isinstance(tombstone, dict) and tombstone.get('sessionEnded') is True,
              'dispose Agent1 后，lifecycle 未出现 Agent1 的 sessionEnded 墓碑')
        second_after = (after_dispose.get('agent2Call')
                        if isinstance(after_dispose.get('agent2Call'), dict) else {})
        second_after_error = as_text(second_after.get('error'))
        check(second_after.get('ok') is False and 'HELPER_MISSING' in second_after_error,
              'dispose Agent1 后，Agent2 的 live turn 未返回 HELPER_MISSING：%s'
              % clip(second_after_error, 400))
        second_turn = after_dispose.get('agent2Turn')
        check(isinstance(second_turn, dict),
              'dispose Agent1 后，state 中找不到 Agent2 的新 turn 记录')
        if isinstance(second_turn, dict):
            check(second_turn.get('sessionEnded') is False,
                  'Agent2 的新 turn 被 Agent1 的墓碑错误标记为 sessionEnded')
            check(second_turn.get('stoppedAt') is None,
                  'Agent2 的新 turn 被 Agent1 的墓碑错误标记为 stopped')

        sessions = [entry.get('sessionId') for entry in evidence['agents'][:working_count]
                    if isinstance(entry.get('sessionId'), str)]
        expected_turns = [session + ':90' for session in sessions]
        check(len(set(expected_turns)) == len(expected_turns),
              '每个 Agent 的 turn requestId 不唯一：%r' % (expected_turns,))
        for expected in expected_turns:
            check(find_turn(state, expected) is not None,
                  'lifecycle state 缺少按 Agent 独立的 turn %s' % expected)

    first = evidence['agents'][0] if evidence['agents'] else {}
    evidence['sessionId'] = first.get('sessionId')
    evidence['toolCount'] = first.get('toolCount')
    evidence['tools'] = agents[0].get('tools') if agents and isinstance(agents[0], dict) else []
    evidence['liveTurnError'] = first.get('liveTurnError')
    evidence['stoppedTurnError'] = first.get('stoppedTurnError')
    evidence['turn90'] = first.get('turn90')
    evidence['tombstone'] = first.get('tombstone')
    evidence['lifecycleCalls'] = report.get('lifecycleCalls')

    check_boot(failures, boot, timeout)
    return failures, evidence


def evaluate(report, state, boot, timeout, state_path, agents_n):
    if agents_n == 1:
        return evaluate_single(report, state, boot, timeout, state_path)
    return evaluate_multi(report, state, boot, timeout, state_path, agents_n)


def print_diagnostics(report, state, boot, diagnostics):
    print('--- 诊断（检查失败，供排查）---', file=sys.stderr, flush=True)
    commands = diagnostics.get('commands') or []
    for record in commands:
        print('[命令] %s -> exit=%s time=%ss' % (record.get('label'), record.get('returncode'),
                                                record.get('timeoutSeconds', '')), file=sys.stderr)
        if record.get('stderr'):
            print('[stderr] ' + record['stderr'], file=sys.stderr)
        if record.get('stdout'):
            print('[stdout] ' + record['stdout'], file=sys.stderr)
    print('--- 宿主 stdout ---\n' + clip(boot.get('stdout') or '{}', 4000), file=sys.stderr)
    print('--- 宿主 stderr ---\n' + clip(boot.get('stderr') or '{}', 4000), file=sys.stderr)
    print('--- 探针结果 ---\n' + clip(json.dumps(report or {}, ensure_ascii=False, indent=2), 12000),
          file=sys.stderr)
    print('--- lifecycle state ---\n' + clip(json.dumps(state or {}, ensure_ascii=False, indent=2), 12000),
          file=sys.stderr)


def main(argv=None):
    args = parse_args(argv)
    started = time.monotonic()

    app, cli, skip_reason = preflight(args)
    if skip_reason:
        summary = {'status': 'skipped', 'reason': skip_reason, 'app': str(args.app),
                   'elapsedSeconds': round(time.monotonic() - started, 2)}
        log('跳过：' + skip_reason)
        print(json.dumps(summary, ensure_ascii=False, indent=2))
        return 0

    external_home = os.environ.get('DSH_HOME')
    if external_home:
        if unsafe_home(external_home):
            message = ('拒绝运行：环境变量 DSH_HOME=%s 指向真实 DSH home（%s）。'
                       '本脚本只允许临时 DSH_HOME，绝不读写用户 ~/.dsh。'
                       '如确认要跑隔离检查，请先取消该变量：'
                       'env -u DSH_HOME -u PYTHONPATH python3 tools/dsh_isolated_check.py'
                       % (external_home, real_dsh_home()))
            summary = {'status': 'refused', 'reason': message, 'elapsedSeconds':
                       round(time.monotonic() - started, 2)}
            log(message)
            print(json.dumps(summary, ensure_ascii=False, indent=2))
            return 2
        log('忽略外部 DSH_HOME=%s，使用本次临时 DSH_HOME（不读写用户 home）' % external_home)

    python = python_executable()
    if python is None:
        message = '拒绝运行：找不到可用的 Python 解释器（sys.executable 为空且 PATH 无 python3）'
        log(message)
        print(json.dumps({'status': 'refused', 'reason': message}, ensure_ascii=False, indent=2))
        return 2

    try:
        temp_root = Path(tempfile.mkdtemp(prefix='qb-dsh-check-', dir=str(temp_parent()))).resolve()
    except (OSError, RuntimeError) as error:
        message = '拒绝运行：无法创建临时目录：%s' % error
        log(message)
        print(json.dumps({'status': 'refused', 'reason': message}, ensure_ascii=False, indent=2))
        return 2

    home = temp_root / 'dsh-home'
    config_dir = temp_root / 'config'
    result_path = temp_root / 'probe-result.json'
    profile = args.profile or ('qb-iso-' + secrets.token_hex(4))
    diagnostics = {}
    failures = []
    report, state, boot = {}, None, {}
    evidence = {}
    summary = {}

    def refuse_and_cleanup(message):
        log('拒绝运行：' + message)
        shutil.rmtree(temp_root, ignore_errors=True)
        print(json.dumps({'status': 'refused', 'reason': message,
                          'elapsedSeconds': round(time.monotonic() - started, 2)},
                         ensure_ascii=False, indent=2))
        return 2

    if not PROFILE_RE.match(profile):
        return refuse_and_cleanup('profile 名不合法：%r（允许字母、数字与 _.:-，1-128 位）' % profile)
    if profile in SHIPPED_PROFILES:
        return refuse_and_cleanup('profile 名 %r 与 DSH 内置 profile 冲突，拒绝运行' % profile)
    real_profile = real_dsh_home() / 'profiles' / profile
    if real_profile.exists():
        return refuse_and_cleanup('profile 名 %r 与用户 ~/.dsh profile 冲突（%s）'
                                  % (profile, real_profile))
    if (home / 'profiles' / profile).exists():
        return refuse_and_cleanup('临时 DSH_HOME 中已存在 profile %r' % profile)

    env = child_env(home)
    state_path = config_dir / 'host-lifecycle/state.json'
    try:
        create_profile(cli, home, profile, root=temp_root, env=env, diagnostics=diagnostics)
        bundle_dir, _plan = render_bundle(temp_root, config_dir, python)
        install_bundle(cli, profile, bundle_dir, env=env, root=temp_root, diagnostics=diagnostics)
        token = secrets.token_hex(6)
        session_ids = ['qb-iso-%s-a%d' % (token, index + 1) for index in range(args.agents)]
        probe_dir = write_probe(temp_root, python=python, config_dir=config_dir,
                                result_path=result_path, session_ids=session_ids)
        install_probe(cli, profile, probe_dir, env=env, root=temp_root, diagnostics=diagnostics)
        overlay = write_overlay(temp_root)
        log('临时根目录：%s（DSH_HOME=%s，configDir=%s）' % (temp_root, home, config_dir))
        boot = boot_host(cli, profile, overlay, root=temp_root, home=home,
                         timeout=args.timeout, result_path=result_path, diagnostics=diagnostics)
        report = read_json(result_path) or {}
        state = read_json(state_path)
        failures, evidence = evaluate(report, state, boot, args.timeout, state_path, args.agents)
    except SetupError as error:
        diagnostics['setupError'] = str(error)
        failures = ['环境准备失败：%s' % error]
        log('环境准备失败：%s' % error)
    except Exception as error:  # noqa: BLE001 - keep diagnostics for an unexpected script bug
        diagnostics['exception'] = traceback.format_exc()
        failures = ['脚本异常：%s' % error]
        log('脚本异常：\n' + traceback.format_exc())

    summary.update({
        'status': 'failed' if failures else 'passed',
        'app': str(app) if app is not None else None,
        'cli': str(cli),
        'profile': profile,
        'dshHome': str(home),
        'sessionId': evidence.get('sessionId'),
        'toolCount': evidence.get('toolCount'),
        'tools': evidence.get('tools'),
        'liveTurnError': evidence.get('liveTurnError'),
        'stoppedTurnError': evidence.get('stoppedTurnError'),
        'lifecycle': {
            'statePath': str(state_path),
            'turnCount': evidence.get('turnCount'),
            'requestIds': evidence.get('requestIds'),
            'turn90': evidence.get('turn90'),
            'tombstone': evidence.get('tombstone'),
            'lifecycleCalls': evidence.get('lifecycleCalls'),
        },
        'boot': {
            'exitCode': boot.get('exitCode'),
            'timedOut': boot.get('timedOut', False),
            'killedAfterResult': boot.get('killedAfterResult', False),
            'stdout': clip(boot.get('stdout') or ''),
            'stderr': clip(boot.get('stderr') or ''),
        },
        'failures': failures,
    })
    if args.agents > 1:
        summary['agentsRequested'] = args.agents
        summary['agents'] = evidence.get('agents')
        summary['concurrency'] = evidence.get('concurrency')
        summary['capacity'] = evidence.get('capacity')
        summary['definitionIsolation'] = evidence.get('definitionIsolation')
        summary['turnCount'] = evidence.get('turnCount')
    if failures:
        print_diagnostics(report, state, boot, diagnostics)
        summary['diagnostics'] = {
            'commands': diagnostics.get('commands', []),
            'setupError': diagnostics.get('setupError'),
            'exception': diagnostics.get('exception'),
        }
    if args.keep:
        summary['tempRoot'] = str(temp_root)
        summary['tempRootKept'] = True
        log('保留临时目录：%s' % temp_root)
    else:
        shutil.rmtree(temp_root, ignore_errors=True)
        summary['tempRoot'] = None
        summary['tempRootKept'] = False
    summary['elapsedSeconds'] = round(time.monotonic() - started, 2)
    log('检查%s（耗时 %.1fs，agents=%d）'
        % ('通过' if not failures else '未通过', summary['elapsedSeconds'], args.agents))
    print(json.dumps(summary, ensure_ascii=False, indent=2, default=str))
    return 0 if not failures else 1


if __name__ == '__main__':
    raise SystemExit(main())
