PROBE_SOURCE = r'''/* Test-only probe generated by tools/dsh_isolated_check.py. */
import fs from 'node:fs'
import { spawnSync } from 'node:child_process'

export const name = 'quietbridge-e2e-probe'
export const inject = ['agents', 'tools']

const RESULT = __RESULT_PATH__
const LIFECYCLE = __LIFECYCLE_PATH__
const CONFIG_DIR = __CONFIG_DIR__
const STATE_PATH = __STATE_PATH__
const PYTHON = __PYTHON_PATH__
const SESSIONS = __SESSION_IDS__
const AGENTS = __AGENT_COUNT__
const CAPACITY = __CAPACITY__

const report = { probe: 'started', time: new Date().toISOString(), done: false, agents: [] }

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

function write() {
  try {
    fs.writeFileSync(RESULT, JSON.stringify(report, null, 2))
  } catch (error) {
    console.error('probe write failed', error)
  }
}

function readState() {
  try {
    return JSON.parse(fs.readFileSync(STATE_PATH, 'utf8'))
  } catch {
    return null
  }
}

function turnsOf(state) {
  const turns = state && state.turns
  return turns && typeof turns === 'object' ? Object.values(turns) : []
}

function findTurn(state, requestId) {
  return turnsOf(state).find((turn) => turn && turn.requestId === requestId) ?? null
}

function findTombstone(state, sessionId) {
  return turnsOf(state).find((turn) => turn && turn.requestId === null &&
    turn.sessionEnded === true && turn.sessionId === sessionId) ?? null
}

async function waitForState(predicate, timeoutMs) {
  const started = Date.now()
  let latest = readState()
  while (Date.now() - started < timeoutMs) {
    latest = readState()
    if (predicate(latest)) return { ok: true, waitedMs: Date.now() - started, state: latest }
    await sleep(200)
  }
  return { ok: false, waitedMs: Date.now() - started, state: latest }
}

function quietbridgeNames(ctx, agent) {
  const definitions = ctx.tools.definitions(agent) ?? []
  return {
    definitions,
    names: definitions
      .map((item) => item.name)
      .filter((name) => String(name).startsWith('quietbridge_')),
  }
}

async function callPermissions(ctx, agent) {
  const tool = ctx.tools.get('quietbridge_permissions', agent)
  if (tool === undefined) return { ok: false, error: 'quietbridge_permissions definition not found' }
  try {
    const value = await tool.execute(
      { action: 'status' },
      { signal: new AbortController().signal, agent },
    )
    return { ok: true, value: JSON.stringify(value).slice(0, 400) }
  } catch (error) {
    return { ok: false, error: String(error?.message ?? error).slice(0, 800) }
  }
}

export async function apply(ctx) {
  write()
  const watchdog = setTimeout(() => {
    report.fatal = report.fatal ?? 'probe watchdog timeout'
    report.done = true
    write()
    process.exit(1)
  }, 120000)
  setTimeout(async () => {
    const handles = []
    const agentRefs = []
    const agents = []
    try {
      // Create Agents sequentially, each with its own sessionId. The bundle's
      // agent/created listener is serial and awaits connector startup, but poll
      // briefly anyway in case the host changes that ordering. Agents beyond the
      // connector budget are expected to end with zero tools.
      for (let i = 0; i < AGENTS; i += 1) {
        let agent
        const handle = await ctx.agents.create({
          sessionId: SESSIONS[i],
          agentOptions: { provider: 'deepseek-account', model: 'deepseek-chat' },
          setup: (_agentCtx, created) => { agent = created },
        })
        handles.push(handle)
        agentRefs.push(agent)
        const record = {
          index: i + 1,
          requestedSessionId: SESSIONS[i],
          created: agent !== undefined,
          id: agent?.id,
          sessionId: agent?.session?.id,
          lifecycleCalls: [],
        }
        const budget = i < CAPACITY ? 15000 : 2500
        const deadline = Date.now() + budget
        let names = []
        let definitions = []
        let queryError
        while (true) {
          try {
            const snapshot = quietbridgeNames(ctx, agent)
            definitions = snapshot.definitions
            names = snapshot.names
          } catch (error) {
            queryError = String(error?.message ?? error)
          }
          if (names.length > 0 || Date.now() >= deadline) break
          await sleep(250)
        }
        record.queryError = queryError
        record.tools = names
        record.toolCount = names.length
        record.toolFingerprint = names.slice().sort().join('|')
        record.definitionCount = definitions.length
        record.toolPresent = ctx.tools.get('quietbridge_permissions', agent) !== undefined
        agents.push(record)
        report.agents = agents
        write()
      }
      report.created = agents.length === AGENTS && agents.every((record) => record.created)
      report.agent = { id: agents[0]?.id, sessionId: agents[0]?.sessionId }
      report.tools = agents[0]?.tools ?? []
      report.toolCount = agents[0]?.toolCount ?? 0
      report.toolPresent = agents[0]?.toolPresent === true
      report.queryError = agents[0]?.queryError
      // Record whether the per-Agent tool handles are distinct objects (the
      // definitions are registered in each Agent scope, not shared globally).
      report.definitionIsolation = []
      for (let i = 0; i < agentRefs.length; i += 1) {
        for (let j = i + 1; j < agentRefs.length; j += 1) {
          const left = ctx.tools.get('quietbridge_permissions', agentRefs[i])
          const right = ctx.tools.get('quietbridge_permissions', agentRefs[j])
          report.definitionIsolation.push({
            agentA: i + 1,
            agentB: j + 1,
            sameDefinitionHandle: left !== undefined && left === right,
            sameToolFingerprint: agents[i]?.toolFingerprint === agents[j]?.toolFingerprint,
          })
        }
      }
      write()

      const working = agents.filter(
        (record) => record.toolCount > 0 && record.toolPresent === true,
      )
      const sendLifecycle = (record, event, turnId) => {
        const result = spawnSync(PYTHON, ['-B', LIFECYCLE, '--config-dir', CONFIG_DIR], {
          input: JSON.stringify({
            event,
            sessionId: record.sessionId,
            agentId: record.id,
            turnId,
          }),
          timeout: 10000,
          encoding: 'utf8',
        })
        const entry = { event, turnId, status: result.status, signal: result.signal }
        if (result.error) entry.error = String(result.error.message ?? result.error)
        if (result.stderr) entry.stderr = String(result.stderr).slice(0, 500)
        record.lifecycleCalls.push(entry)
      }

      // Phase 1: every connector-backed Agent gets its own live turn and call.
      for (const record of working) {
        sendLifecycle(record, 'turn-start', `${record.sessionId}:90`)
        record.liveTurnCall = await callPermissions(ctx, agentRefs[record.index - 1])
      }
      write()

      // Phase 2: cross-Agent isolation. Stop Agent 1's turn, then Agent 2's
      // still-live turn must pass routing (per-Agent turn state, not shared).
      const concurrency = {}
      if (AGENTS >= 2 && working.length >= 2) {
        const first = working[0]
        const second = working[1]
        sendLifecycle(first, 'turn-end', `${first.sessionId}:90`)
        first.stoppedTurnCall = await callPermissions(ctx, agentRefs[first.index - 1])
        second.liveAfterFirstStopped = await callPermissions(ctx, agentRefs[second.index - 1])
        concurrency.afterStopA = {
          agent1Stopped: first.stoppedTurnCall,
          agent2Live: second.liveAfterFirstStopped,
          agent1TurnId: `${first.sessionId}:90`,
          agent2TurnId: `${second.sessionId}:90`,
        }
      }
      for (const record of working) {
        if (record.stoppedTurnCall) continue
        sendLifecycle(record, 'turn-end', `${record.sessionId}:90`)
        record.stoppedTurnCall = await callPermissions(ctx, agentRefs[record.index - 1])
      }
      write()

      // Phase 3: dispose Agent 1, then run a fresh live turn on Agent 2 and
      // snapshot the store to prove Agent 1's tombstone does not stop Agent 2.
      if (AGENTS >= 2 && working.length >= 2) {
        const first = working[0]
        const second = working[1]
        try {
          await handles[first.index - 1].dispose()
          first.disposed = true
        } catch (error) {
          first.disposeError = String(error?.message ?? error)
        }
        const waited = await waitForState(
          (state) => findTombstone(state, first.sessionId) !== null,
          10000,
        )
        const tombstone = waited.state === null
          ? null
          : findTombstone(waited.state, first.sessionId)
        sendLifecycle(second, 'turn-start', `${second.sessionId}:92`)
        second.afterDisposeLiveCall = await callPermissions(ctx, agentRefs[second.index - 1])
        const snapshot = readState()
        const secondTurn = findTurn(snapshot, `${second.sessionId}:92`)
        concurrency.afterDisposeA = {
          agent1TombstoneFound: tombstone !== null,
          agent1TombstoneWaitedMs: waited.waitedMs,
          agent1Tombstone: tombstone === null ? null : {
            requestId: tombstone.requestId,
            reason: tombstone.reason,
            sessionEnded: tombstone.sessionEnded,
            stoppedAt: tombstone.stoppedAt ?? null,
          },
          agent2Call: second.afterDisposeLiveCall,
          agent2Turn: secondTurn === null ? null : {
            requestId: secondTurn.requestId,
            sessionEnded: secondTurn.sessionEnded,
            stoppedAt: secondTurn.stoppedAt ?? null,
          },
        }
        sendLifecycle(second, 'turn-end', `${second.sessionId}:92`)
        second.afterDisposeStoppedCall = await callPermissions(ctx, agentRefs[second.index - 1])
      }
      report.concurrency = concurrency
      write()

      // N=1 keeps the original single-Agent flow: start one real host turn so
      // the session event bridge records it (the isolated profile has no model
      // credentials, so the turn is expected to end with an error).
      if (AGENTS === 1 && agentRefs[0] !== undefined) {
        try {
          const { randomUUID } = await import('node:crypto')
          agentRefs[0].followup({
            role: 'user',
            content: [{ type: 'text', text: 'quietbridge isolated verification turn' }],
            source: { kind: 'user' },
            id: randomUUID(),
          })
          report.turnSent = true
        } catch (error) {
          report.turnError = String(error?.message ?? error)
        }
        write()
        await sleep(5000)
        report.afterTurn = true
        write()
      }

      // Dispose every remaining Agent, then wait for the lifecycle tombstones
      // so the final store is deterministic before the probe exits.
      for (let i = 0; i < agents.length; i += 1) {
        const record = agents[i]
        if (record.disposed) continue
        try {
          await handles[i].dispose()
          record.disposed = true
        } catch (error) {
          record.disposeError = String(error?.message ?? error)
        }
      }
      const expectedTombstones = working.map((record) => record.sessionId)
      const finalWait = await waitForState(
        (state) => expectedTombstones.every(
          (sessionId) => findTombstone(state, sessionId) !== null,
        ),
        10000,
      )
      report.finalStateWait = { ok: finalWait.ok, waitedMs: finalWait.waitedMs }
      report.disposed = agents[0]?.disposed === true
      report.allDisposed = agents.every((record) => record.disposed === true)
      if (working[0]) {
        report.liveTurnCall = working[0].liveTurnCall
        report.stoppedTurnCall = working[0].stoppedTurnCall
        report.lifecycleCalls = working[0].lifecycleCalls
      }
      report.done = true
      report.finishedAt = new Date().toISOString()
      write()
      clearTimeout(watchdog)
      setTimeout(() => process.exit(0), 1000)
    } catch (error) {
      report.agents = agents
      report.created = agents.length === AGENTS
      report.fatal = String(error?.stack ?? error)
      report.done = true
      write()
      clearTimeout(watchdog)
      setTimeout(() => process.exit(1), 1000)
    }
  }, 2500)
}
'''


class SetupError(RuntimeError):
    """A step needed by the check could not be completed."""


def log(message):
    print('[dsh-isolated-check] ' + message, file=sys.stderr, flush=True)


def clip(text, limit=6000):
    text = text if isinstance(text, str) else ''
    return text if len(text) <= limit else text[:limit] + '\n…（已截断）'


def as_text(value):
    if value is None:
        return ''
    if isinstance(value, bytes):
        return value.decode('utf-8', 'replace')
    return str(value)


def read_json(path):
    try:
        return json.loads(Path(path).read_text(encoding='utf-8'))
    except (OSError, ValueError, UnicodeDecodeError):
        return None


def write_json(path, data):
    Path(path).write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def positive_seconds(text):
    try:
        value = float(text)
    except ValueError:
        raise argparse.ArgumentTypeError('需要秒数')
    if value <= 0:
        raise argparse.ArgumentTypeError('需要正数秒数')
    return value


