def write_probe(root, *, python, config_dir, result_path, session_ids):
    probe_dir = root / 'probe'
    probe_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    write_json(probe_dir / 'package.json', PROBE_PACKAGE)
    source = PROBE_SOURCE
    replacements = {
        '__RESULT_PATH__': str(result_path),
        '__LIFECYCLE_PATH__': str((ROOT / LIFECYCLE).resolve()),
        '__CONFIG_DIR__': str(config_dir),
        '__STATE_PATH__': str(config_dir / 'host-lifecycle/state.json'),
        '__PYTHON_PATH__': python,
    }
    for token, value in replacements.items():
        source = source.replace(token, json.dumps(value, ensure_ascii=False))
    source = source.replace('__SESSION_IDS__', json.dumps(list(session_ids), ensure_ascii=False))
    source = source.replace('__AGENT_COUNT__', str(len(session_ids)))
    source = source.replace('__CAPACITY__', str(CAPACITY_LIMIT))
    tokens = tuple(replacements) + ('__SESSION_IDS__', '__AGENT_COUNT__', '__CAPACITY__')
    leftovers = [token for token in tokens if token in source]
    if leftovers:
        raise SetupError('探针模板替换不完整：%s' % ', '.join(leftovers))
    (probe_dir / 'index.js').write_text(source, encoding='utf-8')
    log('已生成测试探针：%s（%d 个 Agent）' % (probe_dir, len(session_ids)))
    return probe_dir


