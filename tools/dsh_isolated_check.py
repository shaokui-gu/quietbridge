#!/usr/bin/env python3
"""Reproduce the isolated DeepSeek Harness live check for the QuietBridge bundle.

One throwaway temp root and one throwaway ``DSH_HOME``: the check never reads or
writes the user's ``~/.dsh``, never installs into a real profile, never starts the
real helper, and never touches the desktop. It renders the real bundle with a
deliberately missing helper path and boots the real host CLI (Electron as Node)
against a temporary ``web`` profile.

What it proves, end to end:
  - the DSH CLI accepts the rendered bundle (link dependency + profile bundle);
  - a host Agent receives all 19 ``quietbridge_*`` tools from the per-agent MCP
    connector started with trusted host identity;
  - an active, lifecycle-recorded turn passes routing and fails on the missing
    helper (``HELPER_MISSING``, not ``SESSION_ROUTING_REQUIRED``);
  - after the turn is ended the same call is rejected with ``TASK_CANCELLED``;
  - the lifecycle store records the turn and the ``agent-disposed`` tombstone;
  - the host process exits cleanly after the probe disposes its Agent.

With ``--agents N`` the same host run creates N Agents sequentially and adds:
  - N <= 3: every Agent gets its own 19 tools, live-turn ``HELPER_MISSING`` and
    stopped-turn ``TASK_CANCELLED``;
  - N >= 2: stopping Agent 1's turn leaves Agent 2's live turn working, and
    disposing Agent 1 writes only Agent 1's tombstone (Agent 2's fresh turn stays
    live), so per-Agent lifecycle state is isolated;
  - N = 4: the fourth Agent is the expected capacity degradation (maxConnectors
    defaults to 3): ``toolCount=0`` is recorded as degraded, not a failure.

Usage (from the repository root):
    env -u PYTHONPATH python3 tools/dsh_isolated_check.py
    env -u PYTHONPATH python3 tools/dsh_isolated_check.py --agents 2
    env -u PYTHONPATH python3 tools/dsh_isolated_check.py --agents 4
    python3 tools/dsh_isolated_check.py --keep          # keep temp dirs
    python3 tools/dsh_isolated_check.py --app /path/to/DeepSeek\\ Harness.app
    python3 tools/dsh_isolated_check.py --timeout 240

Exit codes:
    0  checks passed, or skipped because the DSH app/CLI is not installed
    1  a check failed (diagnostics are printed)
    2  refused: unsafe DSH_HOME / profile name, or no usable temp or Python
"""
